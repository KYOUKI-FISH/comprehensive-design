SELECT 'user'        AS `表`, COUNT(*) AS `行数` FROM `user`
UNION ALL SELECT 'meeting_room', COUNT(*) FROM `meeting_room`
UNION ALL SELECT 'reservation',  COUNT(*) FROM `reservation`;

-- 半开区间教学样例核对：下面这条查询应返回 A301 在 2026-10-14 的占用时段，
-- 可见 09:00-10:00 与 10:00-11:00 是两条独立记录（首尾相接，非冲突）。
SELECT r.`id`, m.`name` AS `会议室`, r.`reserve_date` AS `日期`,
       r.`start_time` AS `开始`, r.`end_time` AS `结束`, r.`status` AS `状态`
FROM `reservation` r
         JOIN `meeting_room` m ON m.`id` = r.`room_id`
WHERE m.`name` = '主楼 A301' AND r.`reserve_date` = '2026-10-14'
  AND r.`status` <> 'CANCELLED'
ORDER BY r.`start_time`;
